export type PixelIconName = keyof typeof ICONS;

/** Rows of a bitmap merged into horizontal runs, so an icon is a handful of rects instead of 144. */
function runs(rows: readonly string[]): { x: number; y: number; w: number }[] {
  const out: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const lit = row[x] === '#';
      if (lit && start < 0) start = x;
      if (!lit && start >= 0) {
        out.push({ x: start, y, w: x - start });
        start = -1;
      }
    }
  });
  return out;
}

const runCache = new Map<PixelIconName, ReturnType<typeof runs>>();
const runsFor = (name: PixelIconName) => {
  const hit = runCache.get(name);
  if (hit) return hit;
  const made = runs(ICONS[name]);
  runCache.set(name, made);
  return made;
};

type PixelIconProps = { name: PixelIconName; size?: number; color: string };

/** One icon from the app's pixel set, crisp at any multiple of 12 dp. */
export const PixelIcon = memo(function PixelIcon({ name, size = 24, color }: PixelIconProps) {
  return (
    <Svg width={size} height={size} viewBox="0 0 12 12">
      {runsFor(name).map((r) => (
        <Rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1.02} fill={color} />
      ))}
    </Svg>
  );
});
